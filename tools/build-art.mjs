// Builds js/art.js from the CC0 guitar drawings in assets/art/.
// Run after adding or changing a drawing: node tools/build-art.mjs
//
// Each drawing is cleaned (editor metadata dropped, numbers rounded, ids prefixed so
// several drawings can share a page) and checked: no scripts, event handlers, external
// links or embedded documents. The body and pickguard get placeholder fills so the
// renderer can recolour them.
import { readFileSync, writeFileSync } from 'node:fs';

// id: file in assets/art, the drawing's body/guard element ids, credit.
const SOURCES = {
  strat: { body: 'path4527', guard: 'path4529', credit: 'piemaster, Wikimedia Commons, CC0 — commons.wikimedia.org/wiki/File:Fender_Stratocaster.svg' },
  lespaul: { body: 'path32016', guard: 'path32018', credit: 'piemaster, Wikimedia Commons, CC0 — commons.wikimedia.org/wiki/File:Gibson_Les_Paul.svg' },
  jazzbass: { body: 'path10963', guard: 'path10965', credit: 'piemaster, Wikimedia Commons, CC0 — commons.wikimedia.org/wiki/File:Fender_Jazz_Bass.svg' },
  jagstang: { body: 'path2212', guard: 'path2214', credit: 'piemaster, Wikimedia Commons, CC0 — commons.wikimedia.org/wiki/File:Fender_Jagstang.svg' },
  sg: { body: 'path11072', guard: 'path11074', credit: 'piemaster, Openclipart, CC0 — openclipart.org/detail/16718' },
  explorer: { body: 'path10052', guard: 'path10056', credit: 'piemaster, Openclipart, CC0 — openclipart.org/detail/16717' },
  flyingv: { body: 'path16426', guard: 'path16428', credit: 'piemaster, Openclipart, CC0 — openclipart.org/detail/16882' },
  gretschjet: { body: 'path32016', guard: 'path16063', credit: 'piemaster, Openclipart, CC0 — openclipart.org/detail/16714' },
};

const out = {};
for (const [key, src] of Object.entries(SOURCES)) {
  let s = readFileSync(new URL(`../assets/art/${key}.svg`, import.meta.url), 'utf8');
  if (/<script|<foreignObject|\son[a-z]+\s*=|(?:xlink:)?href="(?!#)/i.test(s)) throw new Error(`${key}: unsafe content`);
  const root = s.match(/<svg\b[^>]*>/)[0];
  const vb = root.match(/viewBox="([^"]+)"/)?.[1].split(/[\s,]+/).map(Number);
  const [w, h] = vb ? [vb[2], vb[3]] : ['width', 'height'].map(k => parseFloat(root.match(new RegExp(`\\b${k}="([^"]+)"`))[1]));
  s = s.slice(s.indexOf(root) + root.length, s.lastIndexOf('</svg'))
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<metadata[\s\S]*?<\/metadata\s*>/g, '')
    .replace(/<sodipodi:namedview[\s\S]*?(\/>|<\/sodipodi:namedview\s*>)/g, '')
    .replace(/<title[\s\S]*?<\/title\s*>/g, '')
    .replace(/<rdf:RDF[\s\S]*?<\/rdf:RDF\s*>/g, '')
    .replace(/<(\w+):([\w-]+)\b[\s\S]*?<\/\1:\2\s*>/g, '') // other editor-only elements
    .replace(/<\w+:[\w-]+\b[^>]*\/>/g, '')
    .replace(/xlink:href=/g, 'href=')
    .replace(/\s(sodipodi|inkscape):[\w-]+="[^"]*"/g, '');
  const left = s.replace(/xml:space/g, '').match(/<\w+:[\w-]+|\s\w+:[\w-]+=/);
  if (left) throw new Error(`${key}: namespaced markup left: ${left[0]}`);
  // the parts to recolour; their original colours become the defaults
  const fills = {};
  for (const [id, slot] of [[src.body, 'body'], [src.guard, 'guard']]) {
    const re = new RegExp(`(<[^>]*\\bid="${id}"[^>]*>)`);
    const tag = s.match(re)?.[1];
    if (!tag) throw new Error(`${key}: no element #${id}`);
    fills[slot] = tag.match(/fill[:=]"?(#[0-9a-fA-F]{3,6})/)[1];
    s = s.replace(tag, tag.replace(/fill:[^;"]+/, `fill:{{${slot}}}`).replace(/fill="[^"]+"/, `fill="{{${slot}}}"`));
  }
  s = s.replace(/\bid="([^"]+)"/g, `id="${key}-$1"`)
    .replace(/url\(#([^)]+)\)/g, `url(#${key}-$1)`)
    .replace(/href="#([^"]+)"/g, `href="#${key}-$1"`)
    .replace(/\bd="([^"]*)"/g, (m, d) => `d="${d.replace(/(\d+\.\d{2})\d+/g, '$1')}"`) // round path data only: transforms need their precision
    .replace(/\s+/g, ' ').replace(/\s+(\/?>)/g, '$1').replace(/> </g, '><').trim();
  out[key] = { w: +w.toFixed(2), h: +h.toFixed(2), ...fills, svg: s, credit: src.credit };
}

writeFileSync(new URL('../js/art.js', import.meta.url),
  `// Generated by tools/build-art.mjs from assets/art/*.svg — do not edit by hand.\n// All drawings are CC0 (public domain); credits kept below for courtesy.\nexport const ART = ${JSON.stringify(out, null, 1)};\n`);
console.log(Object.entries(out).map(([k, v]) => `${k} ${v.svg.length}B`).join(', '));
